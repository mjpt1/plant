function transliterateLatinToPersian(text: string): string {
  let out = "";
  for (const ch of text) {
    if (CHAR_FA[ch.toLowerCase()]) {
      out += CHAR_FA[ch.toLowerCase()];
    } else if (ch === " " || ch === "-" || ch === "'") {
      out += " ";
    } else if (/[0-9]/.test(ch)) {
      out += ch;
    }
  }
  return out.replace(/\s+/g, " ").trim();
}

function translateByWords(nameEn: string): string | null {
  const words = nameEn.toLowerCase().split(/[\s\-/'(),]+/).filter(Boolean);
  if (words.length === 0) return null;

  const translated = words.map((w) => WORD_FA[w] || null);
  const hitCount = translated.filter(Boolean).length;
  if (hitCount === 0) return null;

  const parts = words.map((w, i) => translated[i] || transliterateLatinToPersian(w));
  return parts.join(" ").replace(/\s+/g, " ").trim();
}

export function getPersianName(nameEn: string, category?: string): string {
  if (PERSIAN_PLANT_NAMES[nameEn]) return PERSIAN_PLANT_NAMES[nameEn];

  const key = Object.keys(PERSIAN_PLANT_NAMES).find(
    (k) => k.toLowerCase() === nameEn.toLowerCase()
  );
  if (key) return PERSIAN_PLANT_NAMES[key];

  const byWords = translateByWords(nameEn);
  if (byWords) return byWords;

  const transliterated = transliterateLatinToPersian(nameEn);
  if (transliterated && transliterated !== nameEn.toLowerCase()) {
    return transliterated;
  }

  if (category && CATEGORY_FA[category]) {
    return `${CATEGORY_FA[category]} ${transliterated || nameEn}`.trim();
  }

  return nameEn;
}

export function getCategoryFa(category: string): string {
  return CATEGORY_FA[category] || category;
}

export function mapWaterRequirement(level?: string): string {
  if (!level) return "";
  const l = level.toLowerCase();
  if (l.includes("low")) return "low";
  if (l.includes("high")) return "high";
  return "medium";
}
